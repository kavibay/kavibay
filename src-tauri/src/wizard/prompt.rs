    /// Two ticked accounts reach the model as two blocks under one heading.
    ///
    /// The whole point of the multi-select: a widget showing room temperatures
    /// with the outdoor temperature under them needs tado° and Open-Meteo, and
    /// a prompt carrying one of them produces a widget that invents the other.
    #[test]
    fn every_ticked_provider_is_spliced() {
        let prompt = contract_system_prompt(&[
            "kavibay.tado/tado".to_string(),
            "kavibay.weather/weather".to_string(),
        ]);

        assert!(
            prompt.contains("The providers this widget reads from"),
            "the heading is plural when there is more than one",
        );
        // A query name from each block, so this fails if either was dropped
        // rather than merely if the heading changed.
        assert!(prompt.contains("zoneStates"), "tado°'s queries are there");
        assert!(prompt.contains("places"), "and Open-Meteo's");
    }

    /// One account keeps the singular heading.
