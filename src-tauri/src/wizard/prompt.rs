    /// The TypeScript side merges an answer onto the package instead of
    /// replacing it, so a file the model leaves out is kept. That only works if
    /// the model has been told the same thing — and the failure is silent in
    /// both directions: an unchanged prompt makes it rewrite whole packages for
    /// nothing, and a half-changed one makes it drop files by omitting them.
    #[test]
    fn both_prompts_say_that_an_omitted_file_is_kept() {
        for (name, prompt) in [
            ("runtime", system_prompt()),
            ("contract", contract_system_prompt(&[])),
        ] {
            assert!(
                prompt.contains("A file you omit is kept, never deleted"),
                "{name}: omission must not read as deletion — mergeGeneratedFiles keeps it"
            );
            assert!(
                prompt.contains("deleted=true"),
                "{name}: the only way left to remove a file has to be named"
            );
            assert!(
                !prompt.contains("a file you\n  omit is a file you deleted"),
                "{name}: the old rule contradicts the merge and must be gone"
            );
            assert!(
                prompt.contains("unless the message says otherwise"),
                "{name}: the partial form is granted per turn, so the prompt must defer to it"
            );
        }
    }

    /// The observed failure was a model that wrote its two sentences of
    /// explanation and stopped — a reply that reads finished, parses to zero
    /// files, and reaches the person as "The answer contained no files."
    /// The prose instruction alone invites it, so the counterweight has to be
    /// present and has to come first.
    #[test]
    fn the_prompt_forbids_an_answer_without_files() {
        let prompt = system_prompt();
        assert!(
            prompt.contains("An answer without file blocks is not an answer"),
            "the rule that catches a model which describes instead of building"
        );
        let rule = prompt
            .find("An answer without file blocks")
            .expect("rule must be present");
        let prose_instruction = prompt
            .find("plain-language explanation")
            .expect("prose instruction must be present");
        assert!(
            rule < prose_instruction,
            "the files-are-mandatory rule must precede the write-an-explanation rule, \
             or the model satisfies the explanation and stops"
        );
    }

    /// Without a worked declaration in front of it, the model treats the network
    /// as unavailable and ships a widget full of invented numbers — the failure
    /// is invisible, because such a widget looks finished. The reference lives in
    /// `PACKAGE_DOC`; what this asserts is that the prompt also *reaches* for it.
    #[test]
    fn the_prompt_teaches_declared_network() {
        let prompt = system_prompt();
        assert!(
            prompt.contains("network.declared") && prompt.contains("path=api.json"),
            "the permission and the file it requires must appear together"
        );
        assert!(
            prompt.contains("kavibay.http(\"pulls\""),
            "a worked call beats a description of one"
        );
        assert!(
            prompt.contains("branch on ok"),
            "http() resolves on provider errors; a model that assumes throw ships no error state"
        );
        assert!(
            prompt.contains("githubPat")
                && prompt.contains("linearApi")
                && prompt.contains("n8nApi")
                && prompt.contains("notionApi")
                && prompt.contains("spotifyOAuth2")
                && prompt.contains("fitbitOAuth2"),
            "a real credential type id, so the model does not invent one that fails validation"
        );
        assert!(
            prompt.contains("Authorization"),
            "the header is the reflex to unlearn — declaring it fails the package"
        );
        // A generated GitHub widget failed on exactly this: `review-requests`.
        // Kebab-case is the natural spelling for an id and the validator refuses
        // it, so the rule has to be in front of the model, not only in the code.
        assert!(
            prompt.contains("No dashes"),
            "the endpoint id charset must reach the model, or it writes kebab-case"
        );
    }

